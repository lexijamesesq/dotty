#!/usr/bin/env bash
# Test suite for git-hooks/vale-self-narration.sh — the enforced self-narration
# prose gate (Vale Estate.SelfNarration + Estate.SelfNarrationProvenance),
# re-homed from the retired qa.py's self-narration scan (slice 2b).
#
# EMPIRICAL by design (a rule that never fires is a vacuous gate worse than none):
# every assertion RUNS the actual wrapper + Vale, never reads config. Proves:
#   * NON-VACUOUS — each rule fires on a real violation. Group 2 (provenance
#     parenthetical) is tested with a by-agent noun that does NOT overlap any
#     group-1 literal ("(written by AI)", "(authored by this skill)"), so an
#     incidental group-1 match cannot mask a dead group-2 regex (the exact defect
#     a naive escaped-paren port ships — it needs Vale's nonword construction);
#   * ZERO-FP — the same phrases inside a fenced block / inline code do NOT trip
#     (Vale's native code-skip, the FP mitigation); and legit prose that merely
#     resembles a token ("As an AI researcher", "(reviewed by the team)", "I am
#     Claudia", "has an AImage") does NOT trip;
#   * WHOLE-TREE — the rule over every tracked markdown in dotty is clean (the
#     pre-commit --all-files bar CI enforces);
#   * FAIL-OPEN — with the vale binary absent from PATH, the wrapper exits 0 with
#     an advisory (CI-authoritative posture).
#
# Rule-correctness tests need the vale binary; when it is absent (a dev running
# run-all.sh without vale) they SKIP with a notice rather than fail — CI installs
# vale (setup-vale) and runs them for real. The fail-open test runs regardless.
#
# shellcheck disable=SC2016
# ^ the fixtures use single-quoted printf with LITERAL backticks (`Generated by
# Claude`) on purpose — markdown code spans, never shell expansions.
set -uo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/lib/assert.sh"

WRAPPER="${WRAPPER:-${SCRIPT_DIR}/../../git-hooks/vale-self-narration.sh}"
[[ -x "$WRAPPER" ]] || { echo "FATAL: missing/!x $WRAPPER"; exit 2; }

TMP="$(mktemp -d -t vale-self-narration-test.XXXXXX)"
cleanup() { chmod -R u+rw "$TMP" 2>/dev/null; rm -rf "$TMP"; }
trap cleanup EXIT INT TERM

# Run the actual shipped wrapper over one fixture; capture exit + Vale output.
run() { OUT="$("$WRAPPER" "$1" 2>&1)"; RC=$?; }

# --- Fail-open (no vale on PATH) — runs whether or not vale is installed --------
section "FAIL-OPEN: wrapper exits 0 with an advisory when vale is absent from PATH"
printf 'Body Generated by Claude — a real violation.\n' > "$TMP/failopen.md"
# /usr/bin:/bin has dirname (the only external tool the wrapper needs) but not
# vale (setup-vale installs to /usr/local/bin), so `command -v vale` fails.
FO_OUT="$(env PATH="/usr/bin:/bin" bash "$WRAPPER" "$TMP/failopen.md" 2>&1)"; FO_RC=$?
assert_eq "fail-open exits 0" "0" "$FO_RC"
printf '%s' "$FO_OUT" | grep -qi "vale not installed" && pass "fail-open prints the advisory" || fail "fail-open advisory" "$FO_OUT"

# --- Rule-correctness (needs vale) ---------------------------------------------
if ! command -v vale >/dev/null 2>&1; then
    echo "  [SKIP] vale not on PATH — rule-correctness tests skipped (CI installs vale via setup-vale)."
    finish
    exit 0
fi

section "NON-VACUOUS group 1: generator self-naming BLOCKS and names Estate.SelfNarration"
printf 'This footer: Generated by Claude at the bottom.\n' > "$TMP/g1.md"
run "$TMP/g1.md"
assert_eq "group-1 violation exits non-zero" "1" "$RC"
printf '%s' "$OUT" | grep -q "Estate.SelfNarration" && pass "names the self-naming rule" || fail "group-1 rule name" "$OUT"

section "NON-VACUOUS group 2: provenance parenthetical BLOCKS (noun NOT overlapping group 1)"
printf 'An inline note (written by AI) here, plus (authored by this skill).\n' > "$TMP/g2.md"
run "$TMP/g2.md"
assert_eq "group-2 violation exits non-zero" "1" "$RC"
printf '%s' "$OUT" | grep -q "Estate.SelfNarrationProvenance" && pass "names the provenance rule (regex is live, not inert)" || fail "group-2 rule name — provenance regex may be INERT" "$OUT"

section "more self-naming forms BLOCK (🤖, Co-Authored-By, I am Claude, As an AI, I)"
printf 'Footer 🤖 Generated with Claude Code here.\n' > "$TMP/g1b.md"; run "$TMP/g1b.md"; assert_eq "robot-generated exits 1" "1" "$RC"
printf 'Trailer Co-Authored-By: Claude noted.\n' > "$TMP/g1c.md"; run "$TMP/g1c.md"; assert_eq "co-authored exits 1" "1" "$RC"
printf 'As an AI, I cannot confirm that.\n' > "$TMP/g1d.md"; run "$TMP/g1d.md"; assert_eq "AI-disclaimer exits 1" "1" "$RC"

section "ZERO-FP: banned phrases inside a fenced block / inline code do NOT trip (code-skip)"
printf 'Example footer:\n```\n🤖 Generated with Claude Code\nCo-Authored-By: Claude\n```\nAnd inline `Generated by Claude` as an example.\n' > "$TMP/fenced.md"
run "$TMP/fenced.md"
assert_eq "fenced + inline-code banned phrases exit 0" "0" "$RC"

section "ZERO-FP: legit prose that resembles a token does NOT trip"
printf 'As an AI researcher, I study models.\nThe report (reviewed by the team) shipped.\nI am Claudia, the maintainer.\nThis has an AImage embedded. The AI wrote a draft we edited.\n' > "$TMP/neg.md"
run "$TMP/neg.md"
assert_eq "look-alike prose exits 0" "0" "$RC"
# Vale always prints a "✔ 0 errors …" summary; a false positive would instead
# name an Estate rule. Assert no rule fired, not that output is empty.
printf '%s' "$OUT" | grep -q "Estate\.SelfNarration" && fail "look-alike prose falsely flagged" "$OUT" || pass "clean prose fires no Estate rule"

section "WHOLE-TREE: the rule over every tracked markdown in dotty is clean (the --all-files bar)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && git rev-parse --show-toplevel 2>/dev/null)" || REPO_ROOT="$SCRIPT_DIR/../.."
TREE_RC=0
if [[ -n "$REPO_ROOT" ]]; then
    # shellcheck disable=SC2046
    ( cd "$REPO_ROOT" && git ls-files -z '*.md' | xargs -0 "$WRAPPER" ) >"$TMP/tree.txt" 2>&1 || TREE_RC=$?
fi
assert_eq "dotty whole-tree markdown scan is clean (exit 0)" "0" "$TREE_RC"
[[ "$TREE_RC" -ne 0 ]] && sed 's/^/    /' "$TMP/tree.txt"

finish
